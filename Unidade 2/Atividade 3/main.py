# Assunto é sobre while

# Imprimindo todos os inteiros de 1 a 100
i = 1
while (i <= 100):
    print(i)
    i = i + 1
print("Fim do programa")

# Imprimindo os inteiros de 1 a n
n = int(input("Digite um númeo inteiro "))
i = 1
while (i <= n):
    print(i)
    i = i + 1
print("End")

# Imprimindo números inteiros de n a 0
n = int(input("Digite um número "))
while (n >= 0):
    print(n)
    n = n - 1
print("BOOM!")
